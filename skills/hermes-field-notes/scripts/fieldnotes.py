def _map_status(raw):
    raw = str(raw or "").strip().lower()
    for key, value in _STATUS_MAP.items():
        if raw.startswith(key):
            return value
    return "active"


def _map_area(raw):
    for token in re.split(r"[|,/ ]+", str(raw or "").lower()):
        if token in AREAS:
            return token
        if token in ("telegram", "line", "discord", "slack", "whatsapp"):
            return "platform"
    return "other"


def migrate_note(path, index_rows):
    """(new_text, problems) for one legacy note: field-notes bullet header or older YAML frontmatter."""
    text = Path(path).read_text(encoding="utf-8").replace("\r\n", "\n").lstrip("\ufeff")
    stem = Path(path).stem
    problems = []
    meta, order, body, errors = split_frontmatter(text) if text.startswith("---\n") else ({}, [], text, [])
    if errors:
        problems.extend(errors)
    if not meta:
        m = re.search(r"\*\*Date:\*\*\s*([\d-]+).*?\*\*Area:\*\*\s*([^·\n]+).*?\*\*Status:\*\*\s*([^·\n]+)", text)
        title = re.search(r"^#\s+(.+)$", text, re.MULTILINE)
        meta = {"title": title.group(1).strip() if title else stem}
        if m:
            meta.update(date=m.group(1), area_raw=m.group(2).strip(), status_raw=m.group(3).strip())
        body = text
    new = {"schema_version": SCHEMA_VERSION, "id": stem,
           "title": str(meta.get("title") or stem),
           "date": str(meta.get("date") or stem[:10]),
           "updated": str(meta.get("updated") or meta.get("date") or stem[:10]),
           "type": meta.get("type") if meta.get("type") in TYPES else "pitfall",
           "area": meta.get("area") if meta.get("area") in AREAS else _map_area(meta.get("area") or meta.get("area_raw")),
           "status": meta.get("status") if meta.get("status") in STATUSES else _map_status(meta.get("status") or meta.get("status_raw")),
           "seen_on": str(meta.get("seen_on") or ""),
           "summary": str(meta.get("summary") or index_rows.get(stem) or "")}
    if not new["summary"]:
        problems.append("no summary found — write one")
    if not re.match(r"^\d{4}-\d{2}-\d{2}$", new["date"]):
        problems.append(f"date '{new['date']}' is not YYYY-MM-DD")
    for key, value in meta.items():
        if key not in new and key not in ("area_raw", "status_raw"):
            new[key] = value  # keep unknown fields as they were
    if meta.get("area") and meta.get("area") not in AREAS:
        new["legacy_area"] = str(meta.get("area"))
    if meta.get("status") and meta.get("status") not in STATUSES:
        new["legacy_status"] = str(meta.get("status"))
    for key in ("area_raw", "status_raw"):
        if meta.get(key):
            new["legacy_" + key[:-4]] = meta[key]
    return dump_frontmatter(new) + ("\n" if not body.startswith("\n") else "") + body, problems


def _index_summaries(index_path):
    rows = {}
    try:
        lines = Path(index_path).read_text(encoding="utf-8").splitlines()
    except OSError:
        return rows
    for line in lines:
        m = re.search(r"\]\((?:notes/)?([^)]+?)\.md\)", line)
        if m and line.startswith("|"):
            cells = [c.strip() for c in re.split(r"(?<!\\)\|", line.strip().strip("|"))]
            if cells:
                rows[Path(m.group(1)).name] = cells[-1].replace("\\|", "|")
    return rows


