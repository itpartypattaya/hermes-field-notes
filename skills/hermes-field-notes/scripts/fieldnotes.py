_KEY_RE = re.compile(r"^([A-Za-z_][A-Za-z0-9_-]*)\s*:(?:\s+(.*))?$")
_DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
_BARE_OK = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.\-/]*$")
_NUMBER_LIKE = re.compile(r"^[-+]?(\d[\d_]*\.?\d*|\.\d+)([eE][-+]?\d+)?$|^0[xXoObB]")
_YAML_WORDS = {"yes", "no", "on", "off", "true", "false", "null", "y", "n", "~"}


def _strip_comment(raw):
    out, quote = [], None
    for i, ch in enumerate(raw):
        if quote:
            out.append(ch)
            if ch == quote and not (quote == '"' and i and raw[i - 1] == "\\"):
                quote = None
            continue
        if ch in "\"'":
            quote = ch
        elif ch == "#" and (i == 0 or raw[i - 1] in " \t"):
            break
        out.append(ch)
    return "".join(out).strip()


def _unquote(token):
    token = token.strip()
    if len(token) >= 2 and token[0] == token[-1] == '"':
        try:
            return json.loads(token)
        except ValueError:
            return token[1:-1]
    if len(token) >= 2 and token[0] == token[-1] == "'":
        return token[1:-1].replace("''", "'")
    return token


def _split_list(inner):
    items, buf, quote = [], [], None
    for ch in inner:
        if quote:
            buf.append(ch)
            if ch == quote:
                quote = None
            continue
        if ch in "\"'":
            quote = ch
            buf.append(ch)
        elif ch == ",":
            items.append("".join(buf))
            buf = []
        else:
            buf.append(ch)
    if "".join(buf).strip():
        items.append("".join(buf))
    return [_unquote(i) for i in items if i.strip()]


def parse_value(raw):
    raw = _strip_comment(raw or "")
    if raw.startswith("[") and raw.endswith("]"):
        return _split_list(raw[1:-1])
    return _unquote(raw)


def split_frontmatter(text):
    """(meta, keys_in_order, body, errors). Notes without frontmatter return an empty meta."""
    text = text.lstrip("\ufeff").replace("\r\n", "\n")
    if not text.startswith("---\n"):
        return {}, [], text, ["no frontmatter (file must start with '---')"]
    end = text.find("\n---", 4)
    if end == -1:
        return {}, [], text, ["frontmatter is not closed with '---'"]
    block = text[4:end]
    rest = text[end + 4:]
    body = rest[1:] if rest.startswith("\n") else rest
    meta, order, errors = {}, [], []
    for n, line in enumerate(block.split("\n"), start=2):
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if line[0] in " \t":
            errors.append(f"line {n}: nested or indented values are not supported")
            continue
        m = _KEY_RE.match(line)
        if not m:
            errors.append(f"line {n}: expected 'key: value'")
            continue
        key = m.group(1)
        if key in meta:
            errors.append(f"line {n}: duplicate key '{key}'")
            continue
        meta[key] = parse_value(m.group(2) or "")
        order.append(key)
    return meta, order, body, errors


def format_scalar(value):
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    text = "" if value is None else str(value)
    if _DATE_RE.match(text):
        return text
    if (_BARE_OK.match(text) and re.search(r"[A-Za-z]", text) and text.lower() not in _YAML_WORDS
            and not _NUMBER_LIKE.match(text)):
        return text
    return json.dumps(text, ensure_ascii=False)


def dump_frontmatter(meta, order=None):
    keys = list(order or []) + [k for k in meta if k not in (order or [])]
    lines = ["---"]
    for key in keys:
        if key not in meta:
            continue
        value = meta[key]
        if isinstance(value, (list, tuple)):
            lines.append(f"{key}: [{', '.join(format_scalar(v) for v in value)}]")
        else:
            lines.append(f"{key}: {format_scalar(value)}")
    lines.append("---")
    return "\n".join(lines) + "\n"


