def safe_target(root, rel):
    """Resolved path of `rel` inside `root`, or None if it escapes the root."""
    rel = str(rel or "").replace("\\", "/")
    if not rel or rel.startswith("/") or re.match(r"^[A-Za-z]:", rel) or ".." in rel.split("/"):
        return None
    root_res = Path(root).resolve()
    path = (Path(root) / rel)
    try:
        resolved = path.resolve()
    except OSError:
        return None
    try:
        resolved.relative_to(root_res)
    except ValueError:
        return None
    return path


def validate_checks(data):
    """List of problems in a parsed checks.json."""
    problems = []
    if not isinstance(data, dict):
        return ["checks file must be a JSON object"]
    editions = data.get("editions")
    if not isinstance(editions, list) or not editions:
        return ["'editions' must be a non-empty list"]
    for i, ed in enumerate(editions):
        where = f"editions[{i}]"
        if not isinstance(ed, dict):
            problems.append(f"{where} must be an object")
            continue
        when = ed.get("when", {})
        if not isinstance(when, dict) or set(when) - {"min_version", "max_version"}:
            problems.append(f"{where}.when may only hold min_version / max_version")
        else:
            for key in ("min_version", "max_version"):
                if when.get(key) and version_tuple(when[key]) is None:
                    problems.append(f"{where}.when.{key} is not a version")
        targets = ed.get("targets")
        if not isinstance(targets, list) or not targets:
            problems.append(f"{where}.targets must be a non-empty list")
            targets = []
        for j, t in enumerate(targets + list(ed.get("upstream") or [])):
            label = f"{where}.targets[{j}]" if j < len(targets) else f"{where}.upstream[{j - len(targets)}]"
            if not isinstance(t, dict) or not isinstance(t.get("file"), str) or not t.get("file"):
                problems.append(f"{label} needs a 'file'")
                continue
            if safe_target(".", t["file"]) is None:
                problems.append(f"{label}.file must be relative to the core root, without '..'")
            for key in ("contains", "not_contains"):
                value = t.get(key, [])
                if not isinstance(value, list) or not all(isinstance(s, str) and s for s in value):
                    problems.append(f"{label}.{key} must be a list of non-empty strings")
            if j < len(targets) and not t.get("contains"):
                problems.append(f"{label}.contains must name at least one sign of the patch")
    return problems


def _edition_for(editions, version):
    """(edition, reason). First edition whose bounds hold wins."""
    vt = version_tuple(version) if version and version != "0.0.0" else None
    bounded = [e for e in editions if (e.get("when") or {}).get("min_version") or (e.get("when") or {}).get("max_version")]
    if vt is None:
        if not bounded:
            return editions[0], None
        unbounded = [e for e in editions if e not in bounded]
        return (unbounded[0], None) if unbounded else (None, "version_unknown")
    for ed in editions:
        when = ed.get("when") or {}
        lo, hi = version_tuple(when.get("min_version")), version_tuple(when.get("max_version"))
        if (lo is None or vt >= lo) and (hi is None or vt <= hi):
            return ed, None
    return None, "n/a"


def _read(path):
    try:
        return path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return None


def check_patch(note, core, root):
    """Static check of one patch note against the core tree. Returns a result dict."""
    result = {"id": note.id, "short": str(note.get("patch_short") or note.title), "kind": str(note.get("patch_kind")),
              "status": "UNKNOWN", "reason": None, "evidence": [], "targets": []}
    try:
        data = json.loads(note.checks_path.read_text(encoding="utf-8-sig"))
    except OSError:
        result["reason"] = "bad_checks"
        result["evidence"].append(f"no checks file {note.checks_path.name}")
        return result
    except ValueError as exc:
        result["reason"] = "bad_checks"
        result["evidence"].append(f"{note.checks_path.name}: {exc}")
        return result
    problems = validate_checks(data)
    if problems:
        result["reason"] = "bad_checks"
        result["evidence"].extend(problems)
        return result
    version = core.get("version_from_tag") or core.get("version")
    edition, why = _edition_for(data["editions"], version)
    if edition is None:
        if why == "n/a":
            result["status"] = "N/A"
            result["evidence"].append(f"no edition applies to {version}")
        else:
            result["reason"] = "version_unknown"
        return result
    result["targets"] = [t["file"] for t in edition["targets"]]
    gone, unreadable, full, partial, absent = [], [], [], [], []
    for t in edition["targets"]:
        path = safe_target(root, t["file"])
        if path is None:
            unreadable.append(t["file"])
            result["evidence"].append(f"{t['file']}: path escapes the core root")
            continue
        if not path.is_file():
            gone.append(t["file"])
            result["evidence"].append(f"{t['file']}: file not found")
            continue
        text = _read(path)
        if text is None:
            unreadable.append(t["file"])
            continue
        found = [s for s in t["contains"] if s in text]
        forbidden = [s for s in t.get("not_contains", []) if s in text]
        missing = [s for s in t["contains"] if s not in text]
        line = f"{t['file']}: {len(found)}/{len(t['contains'])} signs"
        if forbidden:
            line += f", unpatched code present: {', '.join(repr(s[:40]) for s in forbidden)}"
        result["evidence"].append(line)
        if not missing and not forbidden:
            full.append(t["file"])
        elif not found:
            absent.append(t["file"])
        else:
            partial.append(t["file"])
    upstream_rules = edition.get("upstream") or []
    upstream_ok = bool(upstream_rules)
    for rule in upstream_rules:
        path = safe_target(root, rule["file"])
        text = _read(path) if path is not None and path.is_file() else None
        if text is None or not all(s in text for s in rule.get("contains", [])):
            upstream_ok = False
    if upstream_ok:
        result["evidence"].append("upstream signs present")

    if unreadable:
        result["reason"] = "unreadable"
    elif gone:
        if upstream_ok:
            result["status"] = "UPSTREAMED"
        else:
            result["reason"] = "target_gone"
    elif partial:
        result["reason"] = "partial"
    elif full and len(full) == len(edition["targets"]):
        if upstream_ok:
            result["reason"] = "conflict"
        else:
            result["status"] = "OK"
    elif absent and len(absent) == len(edition["targets"]):
        result["status"] = "UPSTREAMED" if upstream_ok else "MISSING"
    else:
        result["reason"] = "partial"  # some targets full, others absent
    return result


def check_patches(ctx, notes, core):
    results = []
    for note in notes:
        if note.is_patch and note.is_live:
            results.append(check_patch(note, core, ctx.hermes_root))
    return results


def patches_exit(results):
    if any(r["status"] == "UNKNOWN" for r in results):
        return EXIT_UNKNOWN
    if any(r["status"] == "MISSING" for r in results):
        return EXIT_MISSING
    return EXIT_OK


