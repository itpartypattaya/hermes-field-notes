INDEX_HEAD = """# Field Notes

Pitfalls with root cause, local patches of the Hermes core, and observations worth keeping.
Each note is a file in `notes/`; its metadata lives in the frontmatter.
Kept by the `hermes-field-notes` skill. Text above the marker line is yours to edit.

"""


def _cell(text):
    return str(text or "").replace("|", "\\|").replace("\n", " ").strip()


def _index_head(current):
    """Text above the generated table: everything above the marker; for an index written by hand
    before this skill, everything above its first table header row; else the default intro."""
    current = current.replace("\r\n", "\n")
    if INDEX_MARKER in current:
        return current.split(INDEX_MARKER)[0]
    lines = current.split("\n")
    for i, line in enumerate(lines):
        if re.match(r"^\|\s*(date|дата)\s*\|", line, re.IGNORECASE):
            head = "\n".join(lines[:i]).rstrip()
            return head + "\n" if head else INDEX_HEAD
    return INDEX_HEAD


def render_index(notes, current=""):
    head = _index_head(current)
    rows = []
    for note in sorted(notes, key=lambda n: (str(n.get("date") or ""), n.id), reverse=True):
        date = str(note.get("date") or "?")
        if note.get("updated") and str(note.get("updated")) != date:
            date += f" · upd. {str(note.get('updated'))[5:]}"
        rows.append(f"| {date} | [{_cell(note.title)}](notes/{note.path.name}) | {_cell(note.type)} | "
                    f"{_cell(note.get('area'))} | {_cell(note.status)} | {_cell(note.get('summary'))} |")
    table = ["| Date | Note | Type | Area | Status | Summary |", "|---|---|---|---|---|---|", *rows]
    return head.rstrip("\n") + "\n\n" + INDEX_MARKER + "\n\n" + "\n".join(table) + "\n"


