def _merge(base, extra):
    out = dict(base)
    for key, value in (extra or {}).items():
        if key.startswith("_"):
            continue  # "_comment" keys of the example file
        if isinstance(value, dict) and isinstance(out.get(key), dict):
            out[key] = _merge(out[key], value)
        else:
            out[key] = value
    return out


class Context:
    """Resolved paths and settings. Precedence everywhere: CLI > env > config file > default."""

    def __init__(self, args):
        explicit_home = getattr(args, "hermes_home", None)
        env_home = os.environ.get("HERMES_HOME")
        if explicit_home:
            self.home = Path(explicit_home).expanduser()
            if not self.home.is_dir():
                raise FieldNotesError(f"--hermes-home does not exist: {self.home}", EXIT_NOTFOUND)
        elif env_home:
            self.home = Path(env_home).expanduser()
        else:
            self.home = Path(os.path.expanduser("~/.hermes"))

        explicit_cfg = getattr(args, "config", None) or os.environ.get("FIELDNOTES_CONFIG")
        self.config_path = Path(explicit_cfg).expanduser() if explicit_cfg else self.home / "field-notes.json"
        file_cfg = {}
        if self.config_path.is_file():
            try:
                file_cfg = json.loads(self.config_path.read_text(encoding="utf-8-sig"))
            except ValueError as exc:
                raise FieldNotesError(f"config is not valid JSON: {self.config_path}: {exc}")
            if not isinstance(file_cfg, dict):
                raise FieldNotesError(f"config must be a JSON object: {self.config_path}")
        elif explicit_cfg:
            raise FieldNotesError(f"config not found: {self.config_path}", EXIT_NOTFOUND)
        self.cfg = _merge(DEFAULTS, file_cfg)

        env_map = {"store_dir": "FIELDNOTES_STORE_DIR", "hermes_root": "FIELDNOTES_HERMES_ROOT",
                   "timezone": "FIELDNOTES_TIMEZONE", "language": "FIELDNOTES_LANGUAGE"}
        for key, var in env_map.items():
            value = os.environ.get(var)
            if value:
                self.cfg[key] = value
        if not os.environ.get("FIELDNOTES_STORE_DIR") and os.environ.get("FIELD_NOTES_DIR") \
                and not file_cfg.get("store_dir"):
            self.cfg["store_dir"] = os.environ.get("FIELD_NOTES_DIR")

        root = getattr(args, "root", None) or self.cfg.get("store_dir") or str(self.home / "field-notes")
        self.store = Path(root).expanduser()
        hroot = getattr(args, "hermes_root", None) or self.cfg.get("hermes_root") or str(self.home / "hermes-agent")
        self.hermes_root = Path(hroot).expanduser()
        self.read_only = bool(getattr(args, "read_only", False))
        self.state_path = self.home / "cache" / "field-notes-state.json"
        self.lock_path = self.home / "cache" / "field-notes.lock"
        self.tz, self.tz_ok = _tz(str(self.cfg.get("timezone") or "UTC"))
        lang = str(self.cfg.get("language") or "en").lower()
        self.lang = lang if lang in STRINGS else "en"

