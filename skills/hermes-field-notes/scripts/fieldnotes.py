class Lock:
    """O_CREAT|O_EXCL lock file next to the state; a lock older than `stale` seconds is broken."""

    def __init__(self, path, stale=600, wait=30):
        self.path, self.stale, self.wait = Path(path), stale, wait
        self.held = False

    def __enter__(self):
        self.path.parent.mkdir(parents=True, exist_ok=True)
        deadline = time.monotonic() + self.wait
        while True:
            try:
                fd = os.open(str(self.path), os.O_CREAT | os.O_EXCL | os.O_WRONLY)
                os.write(fd, str(os.getpid()).encode())
                os.close(fd)
                self.held = True
                return self
            except FileExistsError:
                try:
                    age = time.time() - self.path.stat().st_mtime
                except OSError:
                    continue
                if age > self.stale:
                    try:
                        self.path.unlink()
                    except OSError:
                        pass
                    continue
                if time.monotonic() > deadline:
                    raise FieldNotesError(f"another fieldnotes run holds {self.path}")
                time.sleep(0.2)

    def __exit__(self, *exc):
        if self.held:
            try:
                self.path.unlink()
            except OSError:
                pass


def atomic_write(path, text, mode=None):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + f".tmp{os.getpid()}")
    with open(tmp, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    if mode is not None:
        try:
            os.chmod(tmp, mode)
        except OSError:
            pass
    os.replace(tmp, path)


def load_state(ctx):
    """State dict; a corrupt file is moved aside and a fresh state starts (reported in `_recovered`)."""
    empty = {"schema_version": SCHEMA_VERSION, "core": {"history": []}, "last_check": None,
             "alerts": {}, "dashboard": {}}
    path = ctx.state_path
    if not path.is_file():
        return empty
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
        if not isinstance(data, dict):
            raise ValueError("not an object")
    except (OSError, ValueError) as exc:
        if not ctx.read_only:
            try:
                os.replace(path, path.with_name(path.name + ".corrupt"))
            except OSError:
                pass
        empty["_recovered"] = f"state file was unreadable ({exc}); started a new one"
        return empty
    for key, value in empty.items():
        data.setdefault(key, value)
    data["core"].setdefault("history", [])
    return data


def save_state(ctx, state):
    if ctx.read_only:
        return
    clean = {k: v for k, v in state.items() if not k.startswith("_")}
    atomic_write(ctx.state_path, json.dumps(clean, ensure_ascii=False, indent=1) + "\n", 0o600)


