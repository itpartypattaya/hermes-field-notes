MASKS = [
    (re.compile(r"/home/[^/\s]+"), "~"),
    (re.compile(r"/Users/[^/\s]+"), "~"),
    (re.compile(r"[A-Za-z]:\\Users\\[^\\\s]+", re.IGNORECASE), "~"),
    (re.compile(r"\b(?:\d{1,3}\.){3}\d{1,3}\b"), "<ip>"),
    (re.compile(r"[\w.+-]+@[\w-]+\.[\w.]+"), "<email>"),
    (re.compile(r"-100\d{6,}"), "<chat_id>"),
]


def mask(text):
    for _, pattern in SECRET_PATTERNS:
        text = pattern.sub("<redacted>", text)
    for pattern, repl in MASKS:
        text = pattern.sub(repl, text)
    return text


def _sections(body):
    out, current = {}, None
    for line in body.split("\n"):
        m = re.match(r"^##\s+(.*)$", line)
        if m:
            current = m.group(1).strip().lower()
            out[current] = []
        elif current is not None:
            out[current].append(line)
    return {k: "\n".join(v).strip() for k, v in out.items()}


def _pick(sections, *names):
    for key, value in sections.items():
        if any(key.startswith(n) for n in names) and value:
            return value
    return ""


def issue_draft(note, core):
    sec = _sections(note.body)
    parts = [
        "<!-- DRAFT made by hermes-field-notes. Nothing was posted. Read every line before publishing: "
        "masking catches obvious secrets, paths and addresses only. -->",
        f"## {note.title}", "",
        f"**Hermes version:** {display_version(core)} ({core.get('short') or 'unknown'})", "",
        "### Symptom", _pick(sec, "symptom", "симптом") or "_describe what you saw_", "",
        "### Root cause", _pick(sec, "root cause", "причина") or "_not established_", "",
        "### How to reproduce / verify", _pick(sec, "how to verify", "как проверить", "проверка") or "_steps_", "",
        "### Workaround", _pick(sec, "fix", "workaround", "фикс", "обход") or "_none_", "",
    ]
    return mask("\n".join(parts).rstrip() + "\n")


