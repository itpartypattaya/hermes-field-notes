def _similar(notes, title, limit=3):
    words = set(_tokens(title))
    scored = []
    for n in notes:
        other = set(_tokens(n.title + " " + str(n.get("summary") or "")))
        if words and other:
            j = len(words & other) / len(words | other)
            if j >= 0.15:
                scored.append((j, n))
    return [n for _, n in sorted(scored, key=lambda x: -x[0])[:limit]]


