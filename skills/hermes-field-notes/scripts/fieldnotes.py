_VERSION_RE = re.compile(r'^version\s*=\s*"([^"]+)"', re.MULTILINE)


def version_tuple(text):
    m = re.match(r"^\s*v?(\d+)\.(\d+)(?:\.(\d+))?", str(text or ""))
    if not m:
        return None
    return tuple(int(x or 0) for x in m.groups())


def _git(root, *argv, timeout=20):
    # --no-optional-locks: never refresh the index, so a status/diff stays read-only.
    try:
        proc = subprocess.run(["git", "--no-optional-locks", "-C", str(root), *argv],
                              capture_output=True, text=True, timeout=timeout, stdin=subprocess.DEVNULL)
    except (OSError, subprocess.SubprocessError):
        return None
    if proc.returncode != 0:
        return None
    return proc.stdout


def core_info(ctx):
    root = ctx.hermes_root
    info = {"root": str(root), "exists": root.is_dir(), "version": None, "identity": None,
            "identity_source": None, "short": None, "describe": None, "tag": None, "ahead": None,
            "is_git": False, "bootstrapped_at": None}
    if not info["exists"]:
        return info
    pyproject = root / "pyproject.toml"
    try:
        text = pyproject.read_text(encoding="utf-8")
        m = _VERSION_RE.search(text)
        info["version"] = m.group(1) if m else None
    except OSError:
        text = None
    head = _git(root, "rev-parse", "HEAD")
    if head and re.match(r"^[0-9a-f]{40}$", head.strip()):
        info.update(is_git=True, identity=head.strip(), identity_source="git", short=head.strip()[:7])
        when = _git(root, "log", "-1", "--format=%cI", "HEAD")
        info["commit_date"] = when.strip()[:10] if when else None
        desc = _git(root, "describe", "--tags", "--long")
        if desc:
            desc = desc.strip()
            m = re.match(r"^(.*)-(\d+)-g[0-9a-f]+$", desc)
            if m:
                info.update(describe=desc, tag=m.group(1), ahead=int(m.group(2)))
    elif text is not None:
        digest = hashlib.sha256(text.encode("utf-8")).hexdigest()
        info.update(identity="pyproject:" + digest[:16], identity_source="pyproject-hash", short=digest[:7])
    # Version display: a dev build (0.0.0) is named by its tag when there is one.
    if info["version"] in (None, "0.0.0") and info["tag"]:
        m = re.search(r"v?(\d+\.\d+(?:\.\d+)?)", info["tag"])
        if m:
            info["version_from_tag"] = m.group(1)
    info["bootstrapped_at"] = _bootstrap_time(ctx.home, info["identity"])
    return info


def display_version(core):
    return core.get("version_from_tag") or core.get("version") or "?"


def _bootstrap_time(home, identity):
    """Hermes records each install revision it bootstrapped (internal format, used as a hint only)."""
    if not identity:
        return None
    for path in sorted((home / "installs").glob("*/bootstrap/*.json")):
        try:
            data = json.loads(path.read_text(encoding="utf-8-sig"))
        except (OSError, ValueError):
            continue
        if isinstance(data, dict) and data.get("identity") == identity and data.get("bootstrappedAt"):
            ts = parse_ts(str(data["bootstrappedAt"]))
            if ts is None:
                m = re.match(r"^(.*[+-]\d{2})(\d{2})$", str(data["bootstrappedAt"]))
                ts = parse_ts(f"{m.group(1)}:{m.group(2)}") if m else None
            if ts:
                return iso(ts)
    return None


def record_core(state, core, now):
    """Append the core identity to the history when it changed. Returns the event or None."""
    history = state["core"]["history"]
    if not core.get("identity"):
        return None
    if history and history[-1].get("identity") == core["identity"]:
        return None
    seen_before = any(h.get("identity") == core["identity"] for h in history)
    previous = history[-1] if history else None
    history.append({"identity": core["identity"], "version": display_version(core),
                    "first_seen_at": iso(now), "bootstrapped_at": core.get("bootstrapped_at")})
    del history[:-50]
    if previous is None:
        return None
    return {"kind": "core_rollback" if seen_before else "core_changed",
            "old": previous.get("version"), "old_short": short_identity(previous.get("identity")),
            "new": display_version(core), "new_short": core.get("short")}


def short_identity(identity):
    identity = str(identity or "")
    return identity[len("pyproject:"):][:7] if identity.startswith("pyproject:") else identity[:7]


def updated_at(state, core):
    """(timestamp, source) of the current core: Hermes' own bootstrap record, else first seen by us."""
    if core.get("bootstrapped_at"):
        return parse_ts(core["bootstrapped_at"]), "bootstrap"
    for item in reversed(state["core"]["history"]):
        if item.get("identity") == core.get("identity"):
            return parse_ts(item.get("first_seen_at")), "first-seen"
    return None, None


def previous_core(state, core):
    history = state["core"]["history"]
    for i in range(len(history) - 1, -1, -1):
        if history[i].get("identity") == core.get("identity") and i > 0:
            return history[i - 1]
    return None


