def _tz(name):
    try:
        from zoneinfo import ZoneInfo
        return ZoneInfo(name), True
    except Exception:  # noqa: BLE001 — no tz database (e.g. Windows without tzdata)
        return dt.timezone.utc, name.upper() == "UTC"


def now_utc():
    override = os.environ.get("FIELDNOTES_NOW")  # tests only: ISO timestamp
    if override:
        return dt.datetime.fromisoformat(override).astimezone(dt.timezone.utc)
    return dt.datetime.now(dt.timezone.utc)


def iso(ts):
    return ts.astimezone(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def parse_ts(value):
    if not value:
        return None
    try:
        return dt.datetime.fromisoformat(str(value).replace("Z", "+00:00")).astimezone(dt.timezone.utc)
    except ValueError:
        return None


