class Note:
    def __init__(self, path):
        self.path = Path(path)
        self.id = self.path.stem
        try:
            self.text = self.path.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError) as exc:
            self.text = ""
            self.meta, self.order, self.body, self.errors = {}, [], "", [f"unreadable: {exc}"]
            return
        self.meta, self.order, self.body, self.errors = split_frontmatter(self.text)

    def get(self, key, default=""):
        value = self.meta.get(key, default)
        return default if value is None else value

    @property
    def title(self):
        return str(self.get("title") or self.id)

    @property
    def type(self):
        return str(self.get("type") or "pitfall")

    @property
    def status(self):
        return str(self.get("status") or "active")

    @property
    def is_patch(self):
        return self.type == "patch"

    @property
    def is_live(self):
        return self.status in LIVE_STATUSES

    @property
    def checks_path(self):
        return self.path.with_name(self.id + ".checks.json")

    def date(self, key="date"):
        value = str(self.get(key) or "")
        try:
            return dt.date.fromisoformat(value)
        except ValueError:
            return None


