def diff_events(state, core, results, drift, notes):
    """Alert events for what changed since the previous check (also updates last_check)."""
    events = []
    last = state.get("last_check") or {}
    prev_status = last.get("patches") or {}
    by_id = {n.id: n for n in notes}
    first_run = not last
    for r in results:
        old = prev_status.get(r["id"])
        new = r["status"]
        if new in ("MISSING", "UNKNOWN", "UPSTREAMED") and old != new:
            note = by_id.get(r["id"])
            events.append({"kind": f"patch_{new}", "p": r["short"], "reason": r.get("reason") or "",
                           "cmd": str(note.get("patch_script") or "") if note else ""})
        elif new == "OK" and old in ("MISSING", "UNKNOWN", "UPSTREAMED"):
            events.append({"kind": "patch_back", "p": r["short"]})
    prev_unreg = set(last.get("drift_unregistered") or [])
    unreg = set(drift.get("unregistered") or []) if drift.get("available") else prev_unreg
    new_files = sorted(unreg - prev_unreg)
    if new_files:
        events.append({"kind": "drift_new", "files": ", ".join(new_files[:5]) + ("…" if len(new_files) > 5 else "")})
    elif prev_unreg and not unreg and not first_run:
        events.append({"kind": "drift_clear"})
    state["last_check"] = {"at": iso(now_utc()), "identity": core.get("identity"),
                           "patches": {r["id"]: r["status"] for r in results},
                           "drift_unregistered": sorted(unreg)}
    return events


def format_events(ctx, state, events):
    """Localised alert lines; throttled events are dropped while within alerts.repeat_hours."""
    s = STRINGS[ctx.lang]
    repeat = float((ctx.cfg.get("alerts") or {}).get("repeat_hours") or 24) * 3600
    now = now_utc()
    lines = []
    for ev in events:
        key = ev.get("throttle")
        if key:
            last = parse_ts(state["alerts"].get(key))
            if last and (now - last).total_seconds() < repeat:
                continue
            state["alerts"][key] = iso(now)
        template = s.get("a_" + ev["kind"])
        if not template:
            continue
        values = {k: v for k, v in ev.items() if k != "kind"}
        if ev["kind"] == "patch_MISSING":
            script = ev.get("cmd")
            base = str(ctx.cfg.get("patch_scripts_base") or "")
            if script and base and not os.path.isabs(script):
                script = str(Path(base) / script)
            values["cmd"] = f"python3 {script}" if script else s["cmd_none"]
        try:
            lines.append(template.format(**values))
        except (KeyError, IndexError):
            lines.append(template)
    return lines


