def lint(ctx, notes, core=None):
    """List of (level, where, message); level is 'error', 'warn' or 'stale'."""
    out = []
    ids = {}
    for note in notes:
        where = f"notes/{note.path.name}"
        for err in note.errors:
            out.append(("error", where, err))
        if not note.meta:
            continue
        m = note.meta
        for key in REQUIRED:
            if m.get(key) in (None, "", []):
                out.append(("error", where, f"missing '{key}'"))
        if note.is_patch:
            for key in REQUIRED_PATCH:
                if m.get(key) in (None, ""):
                    out.append(("error", where, f"patch note missing '{key}'"))
        checks = [("type", TYPES), ("area", AREAS), ("status", STATUSES)]
        if note.is_patch:
            checks.append(("patch_kind", PATCH_KINDS))
        for key, allowed in checks:
            if m.get(key) and m.get(key) not in allowed:
                out.append(("error", where, f"{key} '{m.get(key)}' not one of: {', '.join(allowed)}"))
        if str(m.get("id") or "") and str(m.get("id")) != note.id:
            out.append(("error", where, f"id '{m.get('id')}' differs from the file name '{note.id}'"))
        for key in ("date", "updated", "verified_at"):
            if m.get(key) and note.date(key) is None:
                out.append(("error", where, f"{key} must be YYYY-MM-DD"))
        if note.date("updated") and note.date("date") and note.date("updated") < note.date("date"):
            out.append(("error", where, "updated is earlier than date"))
        if not re.match(r"^\d{4}-\d{2}-\d{2}-[a-z0-9][a-z0-9-]*$", note.id):
            out.append(("warn", where, "file name should be YYYY-MM-DD-slug.md"))
        for key in ("title", "summary"):
            if re.match(r"^\s*<.*>\s*$", str(m.get(key) or "")):
                out.append(("warn", where, f"{key} is still the template placeholder"))
        if "{{" in note.text:
            out.append(("warn", where, "template placeholders '{{…}}' left in the note"))
        if len(str(m.get("summary") or "")) > 1000:
            out.append(("warn", where, "summary is longer than 1000 characters — it is one line of the index"))
        if note.is_patch and note.is_live:
            if m.get("patch_kind") in ("customization", "workaround") and not m.get("upstream") \
                    and not m.get("upstream_none_reason"):
                out.append(("warn", where, "no upstream link: add upstream_none_reason"))
            if not note.checks_path.is_file():
                out.append(("error", where, f"no {note.checks_path.name} — the patch cannot be checked"))
            else:
                try:
                    problems = validate_checks(json.loads(note.checks_path.read_text(encoding="utf-8-sig")))
                except ValueError as exc:
                    problems = [f"not valid JSON: {exc}"]
                for p in problems:
                    out.append(("error", f"notes/{note.checks_path.name}", p))
        ids.setdefault(note.id[11:], []).append(note.id)
        for link in re.findall(r"\]\(([^)\s#]+\.md)(?:#[^)]*)?\)", note.body):
            if "://" in link:
                continue
            if not (note.path.parent / link).resolve().is_file():
                out.append(("warn", where, f"broken link: {link}"))
        for label, pattern in SECRET_PATTERNS:
            if pattern.search(note.text):
                out.append(("error", where, f"looks like a secret ({label}) — mask it"))
        if core and core.get("identity") and note.is_live and m.get("verified_identity"):
            vid = str(m.get("verified_identity"))
            if not core["identity"].startswith(vid) and not str(core.get("short") or "").startswith(vid):
                out.append(("stale", where, f"verified on {vid}, core is now {core.get('short')}"))
    for slug, same in ids.items():
        if len(same) > 1:
            out.append(("warn", "notes/", f"same slug '{slug}' in {', '.join(same)} — update one note instead"))
    index = ctx.store / "INDEX.md"
    if notes:
        current = index.read_text(encoding="utf-8") if index.is_file() else ""
        if render_index(notes, current) != current.replace("\r\n", "\n"):
            out.append(("warn", "INDEX.md", "out of date — run `fieldnotes.py index`"))
    return out


